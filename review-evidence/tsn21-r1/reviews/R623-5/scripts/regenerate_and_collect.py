#!/usr/bin/env python3
"""Regenerate integration artifacts and collect focused executable receipts."""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

packet=Path(__file__).resolve().parents[1]
root=packet/'scratch/integration'
build=packet/'scratch/build-integration'
env=dict(os.environ,PYTHONDONTWRITEBYTECODE='1')
tracked=['docs/REQUIREMENTS.md','docs/TRACEABILITY.md','docs/TESTS.md','tests/coverage.ratchet']
tracked += [str(p.relative_to(root)) for p in (root/'examples/entities').rglob('*') if p.is_file()]
before={p:(root/p).read_bytes() for p in tracked}
results=[]
def run(label,args):
    with (packet/'receipts'/('integration-'+label+'.log')).open('w') as log:
        rc=subprocess.run([sys.executable,*args],cwd=root,env=env,stdout=log,stderr=subprocess.STDOUT,timeout=540).returncode
    (packet/'receipts'/('integration-'+label+'.rc')).write_text(str(rc)+'\n')
    results.append(dict(gate=label,rc=rc))
    if rc:raise RuntimeError(label)
def generate():
    run('regenerate-traceability',['scripts/traceability.py','--write','--build',str(build),'--jobs','4'])
    run('regenerate-inventory',['scripts/test_inventory.py','--write','--build',str(build),'--jobs','4'])
    run('regenerate-coverage',['scripts/coverage.py',str(build),'--write'])
    run('regenerate-entities',['scripts/entity_yaml.py','--examples'])
def entities():
    run('entity-controls',['scripts/entity_selftest.py','--work',str(packet/'scratch/entity-controls')])
with ThreadPoolExecutor(max_workers=2) as pool:
    f=[pool.submit(fn) for fn in (generate,entities)]
    for x in f:x.result()
equal={p:(root/p).read_bytes()==data for p,data in before.items()}
if not all(equal.values()):raise RuntimeError('generated bytes differ')
(packet/'receipts/regeneration.json').write_text(json.dumps(dict(gates=results,byte_identical=equal),indent=2)+'\n')
for target in ('port','integration'):
    for kind in ('mutations','rv32','cache'):
        work=packet/'scratch'/(kind+'-'+target)
        destination=packet/'receipts'/('executed-'+target)/kind
        for path in work.rglob('*'):
            if not path.is_file() or 'source' in path.relative_to(work).parts:continue
            if path.suffix in ('.log','.rc','.xml','.json'):
                dest=destination/path.relative_to(work)
                dest.parent.mkdir(parents=True,exist_ok=True)
                shutil.copyfile(path,dest)
print('All generated artifacts reproduce exact integration bytes; focused receipts collected.')
